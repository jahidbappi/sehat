"""Model-card rendering from evaluation metrics and metadata.

The canonical template lives at ``docs/model_card_template.md`` (owned by
the docs worker). When it is not present — e.g. when this package is used
standalone — a sensible embedded default is used instead. Templates use
``{{ placeholder }}`` tokens, substituted from a merged metrics + metadata
context; unknown placeholders render as ``N/A``.
"""

from __future__ import annotations

import datetime
import json
import math
import re
from pathlib import Path
from typing import Any

__all__ = ["DEFAULT_MODEL_CARD_TEMPLATE", "render_model_card", "write_model_card"]

DEFAULT_MODEL_CARD_TEMPLATE = """# Model Card: {{ model_name }}

## Model Details
- **Model:** {{ model_name }} (architecture: `{{ arch }}`)
- **Version:** {{ version }}
- **Checkpoint:** `{{ checkpoint }}`
- **Developed by:** {{ developers }}
- **Date:** {{ date }}
- **License:** {{ license }}

## Intended Use
- **Primary use:** {{ intended_use }}
- **Primary users:** {{ users }}
- **Out-of-scope uses:** {{ out_of_scope }}

## Training & Evaluation Data
- **Training data:** {{ training_data }}
- **Evaluation data:** {{ eval_data }}
- **Evaluation split size:** {{ n_eval }}

## Performance
| Metric | Value |
| --- | --- |
| AUROC | {{ auroc }} |
| Average precision | {{ average_precision }} |
| Sensitivity @ 95% specificity | {{ sensitivity_at_95spec }} |
| Expected calibration error (15 bins) | {{ ece }} |
| Brier score | {{ brier }} |

## Fairness (subgroup performance)
{{ subgroup_table }}

Disparity flags are raised when a subgroup underperforms the pooled metric
by more than the configured margin; see `eval_report.json` for bootstrap
confidence intervals.

## Calibration
{{ calibration_notes }}

## Limitations
{{ limitations }}

## Ethical Considerations
{{ ethical_considerations }}

## Caveats & Recommendations
{{ caveats }}

---
*Generated by Project Sehat (`sehat.eval`) on {{ generated_at }}.*
"""

_TOKEN_RE = re.compile(r"\{\{\s*([a-zA-Z0-9_]+)\s*\}\}")

# Worker 5's docs/model_card_template.md uses <snake_case_token> placeholders
# and documents that tokens left in angle brackets after rendering must be
# filled in by hand — so unknown angle tokens are preserved, not blanked.
_ANGLE_TOKEN_RE = re.compile(r"<([a-z][a-z0-9_]*)>")

# Metadata key aliases into the docs template's token namespace.
_METADATA_ALIASES = {
    "arch": "architecture",
    "version": "model_version",
    "date": "release_date",
}


def _disease_token_affix(disease: Any) -> str | None:
    """Map a disease name to the template's token affix (``tb`` / ``pna``)."""
    if not isinstance(disease, str):
        return None
    lowered = disease.strip().lower()
    if lowered in ("tb", "tuberculosis"):
        return "tb"
    if lowered in ("pna", "pneumonia"):
        return "pna"
    return None


def _default_template_path() -> Path:
    # src/sehat/eval/model_card.py -> repo root is parents[3].
    return Path(__file__).resolve().parents[3] / "docs" / "model_card_template.md"


def _format_number(value: Any) -> str:
    if isinstance(value, float):
        if math.isnan(value):
            return "N/A"
        return f"{value:.4f}"
    return str(value)


def subgroup_markdown_table(subgroups: dict[str, dict[str, Any]]) -> str:
    """Render the flattened ``subgroups`` mapping as a markdown table.

    Args:
        subgroups: mapping of ``"col:level"`` to ``{"auroc", ...}``, as
            produced by :func:`sehat.eval.report.evaluate_predictions`.
            Entries may also carry ``auroc_ci`` / ``sens_at_95spec_ci`` and a
            ``disparity`` flag dict; both are shown when present.
    """
    if not subgroups:
        return "_No subgroup analysis available._"
    header = (
        "| Subgroup | N | AUROC | AUROC 95% CI | Sens @ 95% spec | Sens 95% CI | Flags |\n"
        "| --- | --- | --- | --- | --- | --- | --- |"
    )
    rows = [header]
    for name, entry in subgroups.items():
        ci_auroc = entry.get("auroc_ci")
        ci_sens = entry.get("sens_at_95spec_ci")
        flags = []
        disparity = entry.get("disparity") or {}
        if disparity.get("auroc"):
            flags.append("AUROC disparity")
        if disparity.get("sens_at_95spec"):
            flags.append("sensitivity disparity")
        if entry.get("insufficient_data"):
            flags.append("insufficient data")
        rows.append(
            "| {name} | {n} | {auroc} | {auroc_ci} | {sens} | {sens_ci} | {flags} |".format(
                name=name,
                n=entry.get("n", "N/A"),
                auroc=_format_number(entry.get("auroc", float("nan"))),
                auroc_ci=_format_ci(ci_auroc),
                sens=_format_number(entry.get("sens_at_95spec", float("nan"))),
                sens_ci=_format_ci(ci_sens),
                flags=", ".join(flags) if flags else "—",
            )
        )
    return "\n".join(rows)


def _format_ci(ci: Any) -> str:
    if not isinstance(ci, (list, tuple)) or len(ci) != 2:
        return "N/A"
    lo, hi = ci
    if not (isinstance(lo, (int, float)) and isinstance(hi, (int, float))):
        return "N/A"
    if math.isnan(lo) or math.isnan(hi):
        return "N/A"
    return f"[{lo:.4f}, {hi:.4f}]"


def _build_context(metrics: dict[str, Any], metadata: dict[str, Any]) -> dict[str, str]:
    context: dict[str, str] = {
        "model_name": "Sehat chest X-ray screening model",
        "version": "0.1.0",
        "arch": "N/A",
        "checkpoint": "N/A",
        "developers": "Project Sehat contributors",
        "date": "N/A",
        "license": "N/A",
        "intended_use": (
            "Assistive triage of chest X-rays for TB and pneumonia in "
            "low-resource clinics; not a standalone diagnostic."
        ),
        "users": "Clinicians and trained screening staff",
        "out_of_scope": "Final diagnosis, paediatric populations, non-CXR imaging",
        "training_data": "N/A",
        "eval_data": "N/A",
        "limitations": "N/A",
        "ethical_considerations": "N/A",
        "caveats": "Always confirm positive screens with standard diagnostic workflows.",
        "calibration_notes": "See reliability-diagram data in the evaluation report.",
    }
    context.update({k: _format_number(v) for k, v in metadata.items()})
    for src_key, dst_key in _METADATA_ALIASES.items():
        if src_key in metadata:
            context[dst_key] = _format_number(metadata[src_key])
    for key in ("auroc", "average_precision", "sensitivity_at_95spec", "ece", "brier"):
        if key in metrics:
            context[key] = _format_number(metrics[key])
    # Map this run's headline metrics onto the docs template's
    # disease/site-specific tokens for the internal test split.
    affix = _disease_token_affix(metadata.get("disease"))
    if affix is not None:
        disease_map = {
            f"auroc_{affix}_internal": metrics.get("auroc"),
            f"sens_at_95spec_{affix}_internal": metrics.get("sensitivity_at_95spec"),
            f"ece_{affix}_internal": metrics.get("ece"),
        }
        for token, value in disease_map.items():
            if value is not None:
                context.setdefault(token, _format_number(value))
    subgroups = metrics.get("subgroups") or {}
    context.setdefault("subgroup_table", subgroup_markdown_table(subgroups))
    context["generated_at"] = datetime.datetime.now(datetime.timezone.utc).strftime(
        "%Y-%m-%d %H:%M UTC"
    )
    return context


def render_model_card(
    metrics: dict[str, Any],
    metadata: dict[str, Any] | None = None,
    template_path: str | Path | None = None,
) -> str:
    """Render a model-card markdown document.

    Args:
        metrics: evaluation metrics dict (the contract schema from
            ``evaluate_predictions``; ``subgroups`` is rendered as a table).
        metadata: free-form metadata (model name, arch, checkpoint, dataset,
            limitations, ...). Values override default context entries.
        template_path: explicit template file. When omitted,
            ``docs/model_card_template.md`` is used if it exists, otherwise
            the embedded :data:`DEFAULT_MODEL_CARD_TEMPLATE`.

    Returns:
        Rendered markdown string.
    """
    if template_path is not None:
        template = Path(template_path).read_text(encoding="utf-8")
    else:
        default_path = _default_template_path()
        template = (
            default_path.read_text(encoding="utf-8")
            if default_path.is_file()
            else DEFAULT_MODEL_CARD_TEMPLATE
        )
    context = _build_context(metrics, metadata or {})
    rendered = _TOKEN_RE.sub(lambda m: context.get(m.group(1), "N/A"), template)
    return _ANGLE_TOKEN_RE.sub(lambda m: context.get(m.group(1), m.group(0)), rendered)


def write_model_card(
    out_path: str | Path,
    metrics: dict[str, Any],
    metadata: dict[str, Any] | None = None,
    template_path: str | Path | None = None,
) -> Path:
    """Render the model card and write it to ``out_path``. Returns the path."""
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_model_card(metrics, metadata, template_path), encoding="utf-8")
    return out


def metrics_from_json(path: str | Path) -> dict[str, Any]:
    """Load a metrics dict (e.g. an ``eval_report.json``) from disk."""
    return json.loads(Path(path).read_text(encoding="utf-8"))
